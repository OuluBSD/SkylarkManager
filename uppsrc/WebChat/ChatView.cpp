String WebChatView::GetClientScript()
{
	String s = GetMarkdownScript();
	s <<
		"var currentSessionId = '';\n"
		"var eventSource = null;\n"
		"var currentStreamBubble = null;\n"
		"var currentStreamBuffer = '';\n"
		"\n"
		"/* Numbered Pagination Controller */\n"
		"var ChatPagination = {\n"
		"  pageSize: 10,\n"
		"  currentPage: 'live',\n"
		"\n"
		"  getTotalMessages: function() {\n"
		"    return document.querySelectorAll('#chat-thread .message-row').length;\n"
		"  },\n"
		"\n"
		"  getTotalPages: function() {\n"
		"    let total = this.getTotalMessages();\n"
		"    return Math.max(1, Math.ceil(total / this.pageSize));\n"
		"  },\n"
		"\n"
		"  goTo: function(target) {\n"
		"    let totalPages = this.getTotalPages();\n"
		"    if (target === 'first') {\n"
		"      this.currentPage = 1;\n"
		"    } else if (target === 'prev') {\n"
		"      if (this.currentPage === 'live') {\n"
		"        this.currentPage = Math.max(1, totalPages - 1);\n"
		"      } else {\n"
		"        this.currentPage = Math.max(1, this.currentPage - 1);\n"
		"      }\n"
		"    } else if (target === 'next') {\n"
		"      if (this.currentPage !== 'live') {\n"
		"        if (this.currentPage >= totalPages) {\n"
		"          this.currentPage = 'live';\n"
		"        } else {\n"
		"          this.currentPage++;\n"
		"        }\n"
		"      }\n"
		"    } else if (target === 'last' || target === 'live') {\n"
		"      this.currentPage = 'live';\n"
		"    } else if (typeof target === 'number') {\n"
		"      this.currentPage = Math.max(1, Math.min(totalPages, target));\n"
		"    }\n"
		"    this.update();\n"
		"  },\n"
		"\n"
		"  update: function() {\n"
		"    let rows = document.querySelectorAll('#chat-thread .message-row');\n"
		"    let total = rows.length;\n"
		"    let totalPages = Math.max(1, Math.ceil(total / this.pageSize));\n"
		"\n"
		"    if (this.currentPage !== 'live') {\n"
		"      if (this.currentPage > totalPages) this.currentPage = totalPages;\n"
		"      if (this.currentPage < 1) this.currentPage = 1;\n"
		"    }\n"
		"\n"
		"    let startIndex = 0;\n"
		"    let endIndex = total;\n"
		"    let isLive = (this.currentPage === 'live');\n"
		"\n"
		"    if (isLive) {\n"
		"      // Live view: latest pageSize messages visible, older paged out visually\n"
		"      startIndex = Math.max(0, total - this.pageSize);\n"
		"      endIndex = total;\n"
		"    } else {\n"
		"      startIndex = (this.currentPage - 1) * this.pageSize;\n"
		"      endIndex = Math.min(total, startIndex + this.pageSize);\n"
		"    }\n"
		"\n"
		"    rows.forEach(function(row, idx) {\n"
		"      if (idx >= startIndex && idx < endIndex) {\n"
		"        row.style.display = 'flex';\n"
		"      } else {\n"
		"        row.style.display = 'none';\n"
		"      }\n"
		"    });\n"
		"\n"
		"    this.renderControls(total, totalPages, startIndex, endIndex, isLive);\n"
		"    if (isLive) scrollToBottom();\n"
		"  },\n"
		"\n"
		"  renderControls: function(total, totalPages, startIndex, endIndex, isLive) {\n"
		"    let info = document.getElementById('pagination-info');\n"
		"    if (info) {\n"
		"      let count = Math.max(0, endIndex - startIndex);\n"
		"      if (isLive) {\n"
		"        info.textContent = 'Live Window: latest ' + count + ' of ' + total + ' messages (Page ' + totalPages + '/' + totalPages + ')';\n"
		"      } else {\n"
		"        info.textContent = 'Showing messages ' + (total > 0 ? (startIndex + 1) : 0) + '-' + endIndex + ' of ' + total + ' (Page ' + this.currentPage + '/' + totalPages + ')';\n"
		"      }\n"
		"    }\n"
		"    let nav = document.getElementById('page-numbers');\n"
		"    if (nav) {\n"
		"      nav.replaceChildren();\n"
		"      for (let p = 1; p <= totalPages; p++) {\n"
		"        let activeClass = (!isLive && this.currentPage === p) ? ' active' : '';\n"
		"        let button = document.createElement('button');\n"
		"        button.type = 'button';\n"
		"        button.className = 'page-btn' + activeClass;\n"
		"        button.textContent = String(p);\n"
		"        button.addEventListener('click', function() { ChatPagination.goTo(p); });\n"
		"        nav.appendChild(button);\n"
		"      }\n"
		"    }\n"
		"    let liveBtn = document.getElementById('btn-page-live');\n"
		"    if (liveBtn) {\n"
		"      if (isLive) liveBtn.classList.add('active');\n"
		"      else liveBtn.classList.remove('active');\n"
		"    }\n"
		"  }\n"
		"};\n"
		"\n"
		"/* Message Actions: Copy, Fork, Revert, Retry, Delete */\n"
		"function copyMessageText(btn) {\n"
		"  let row = btn.closest('.message-row');\n"
		"  if (!row) return;\n"
		"  let raw = row.querySelector('.raw-markdown');\n"
		"  let text = raw ? raw.value : '';\n"
		"  if (!text) {\n"
		"    let body = row.querySelector('.markdown-body');\n"
		"    text = body ? body.innerText : '';\n"
		"  }\n"
		"  navigator.clipboard.writeText(text).then(() => {\n"
		"    let old = btn.textContent;\n"
		"    btn.textContent = 'Copied!';\n"
		"    setTimeout(() => { btn.textContent = old; }, 1500);\n"
		"  });\n"
		"}\n"
		"\n"
		"function forkMessage(btn) {\n"
		"  let row = btn.closest('.message-row');\n"
		"  if (!row) return;\n"
		"  let msgId = row.getAttribute('data-msg-id');\n"
		"  if (!currentSessionId || !msgId) return;\n"
		"  fetch('/api/chat/fork', {\n"
		"    method: 'POST',\n"
		"    headers: {'Content-Type': 'application/json'},\n"
		"    body: JSON.stringify({session_id: currentSessionId, message_id: msgId})\n"
		"  }).then(r => r.json()).then(data => {\n"
		"    if (data.success && data.session && data.session.id) {\n"
		"      selectSession(data.session.id);\n"
		"    } else {\n"
		"      alert('Fork failed: ' + (data.error || 'Server error'));\n"
		"    }\n"
		"  }).catch(err => alert('Fork error: ' + err));\n"
		"}\n"
		"\n"
		"function revertToMessage(btn) {\n"
		"  let row = btn.closest('.message-row');\n"
		"  if (!row) return;\n"
		"  let msgId = row.getAttribute('data-msg-id');\n"
		"  if (!currentSessionId || !msgId) return;\n"
		"  if (!confirm('Revert conversation to this checkpoint? All later messages will be deleted.')) return;\n"
		"  fetch('/api/chat/revert', {\n"
		"    method: 'POST',\n"
		"    headers: {'Content-Type': 'application/json'},\n"
		"    body: JSON.stringify({session_id: currentSessionId, message_id: msgId})\n"
		"  }).then(r => r.json()).then(data => {\n"
		"    if (data.success) {\n"
		"      let next = row.nextElementSibling;\n"
		"      while (next) {\n"
		"        let toRem = next;\n"
		"        next = next.nextElementSibling;\n"
		"        toRem.remove();\n"
		"      }\n"
		"      ChatPagination.update();\n"
		"    } else {\n"
		"      alert('Revert failed');\n"
		"    }\n"
		"  }).catch(err => alert('Revert error: ' + err));\n"
		"}\n"
		"\n"
		"function retryMessage(btn) {\n"
		"  let row = btn.closest('.message-row');\n"
		"  if (!row) return;\n"
		"  let isUser = row.classList.contains('user');\n"
		"  let raw = row.querySelector('.raw-markdown');\n"
		"  let text = raw ? raw.value : '';\n"
		"  if (isUser) {\n"
		"    let input = document.getElementById('chat-input');\n"
		"    if (input) {\n"
		"      input.value = text;\n"
		"      input.focus();\n"
		"    }\n"
		"  } else {\n"
		"    let prev = row.previousElementSibling;\n"
		"    while (prev && !prev.classList.contains('user')) {\n"
		"      prev = prev.previousElementSibling;\n"
		"    }\n"
		"    if (prev) {\n"
		"      let prevRaw = prev.querySelector('.raw-markdown');\n"
		"      let prompt = prevRaw ? prevRaw.value : '';\n"
		"      if (prompt) {\n"
		"        let prevMsgId = prev.getAttribute('data-msg-id');\n"
		"        fetch('/api/chat/revert', {\n"
		"          method: 'POST',\n"
		"          headers: {'Content-Type': 'application/json'},\n"
		"          body: JSON.stringify({session_id: currentSessionId, message_id: prevMsgId})\n"
		"        }).then(r => r.json()).then(data => {\n"
		"          if (data.success) {\n"
		"            row.remove();\n"
		"            ChatPagination.update();\n"
		"            startChatStream(currentSessionId, prompt);\n"
		"          }\n"
		"        });\n"
		"      }\n"
		"    }\n"
		"  }\n"
		"}\n"
		"\n"
		"function deleteMessage(btn) {\n"
		"  let row = btn.closest('.message-row');\n"
		"  if (!row) return;\n"
		"  let msgId = row.getAttribute('data-msg-id');\n"
		"  if (!currentSessionId || !msgId) return;\n"
		"  if (!confirm('Delete this message?')) return;\n"
		"  fetch('/api/chat/message/delete', {\n"
		"    method: 'POST',\n"
		"    headers: {'Content-Type': 'application/json'},\n"
		"    body: JSON.stringify({session_id: currentSessionId, message_id: msgId})\n"
		"  }).then(r => r.json()).then(data => {\n"
		"    if (data.success) {\n"
		"      row.remove();\n"
		"      ChatPagination.update();\n"
		"    }\n"
		"  });\n"
		"}\n"
		"\n"
		"function scrollToBottom() {\n"
		"  let thread = document.getElementById('chat-thread');\n"
		"  if (thread) thread.scrollTop = thread.scrollHeight;\n"
		"}\n"
		"\n"
		"function appendMessage(role, sender, text, isStreaming, msgId) {\n"
		"  let thread = document.getElementById('chat-thread');\n"
		"  let row = document.createElement('div');\n"
		"  row.className = 'message-row ' + role;\n"
		"  if (!msgId) msgId = 'msg-' + Date.now() + '-' + Math.floor(Math.random() * 10000);\n"
		"  row.setAttribute('data-msg-id', msgId);\n"
		"\n"
		"  let avatar = document.createElement('div');\n"
		"  avatar.className = 'avatar ' + role;\n"
		"  avatar.textContent = role === 'user' ? 'U' : 'A';\n"
		"\n"
		"  let contentBox = document.createElement('div');\n"
		"  contentBox.style.display = 'flex';\n"
		"  contentBox.style.flexDirection = 'column';\n"
		"  contentBox.style.maxWidth = '100%';\n"
		"\n"
		"  let senderEl = document.createElement('div');\n"
		"  senderEl.className = 'message-sender';\n"
		"  senderEl.innerText = sender;\n"
		"\n"
		"  let bubble = document.createElement('div');\n"
		"  bubble.className = 'message-bubble';\n"
		"\n"
		"  let rawTextarea = document.createElement('textarea');\n"
		"  rawTextarea.className = 'raw-markdown';\n"
		"  rawTextarea.style.display = 'none';\n"
		"  rawTextarea.value = text;\n"
		"  bubble.appendChild(rawTextarea);\n"
		"\n"
		"  let bodyEl = document.createElement('div');\n"
		"  bodyEl.className = 'markdown-body';\n"
		"  setMessageText(bodyEl, text, isStreaming);\n"
		"  bubble.appendChild(bodyEl);\n"
		"\n"
		"  let actionsEl = document.createElement('div');\n"
		"  actionsEl.className = 'message-actions';\n"
		"  [\n"
		"    {label: 'Copy message text', text: 'Copy', action: copyMessageText},\n"
		"    {label: 'Fork new chat branch from this message', text: 'Fork', action: forkMessage},\n"
		"    {label: 'Revert conversation to this checkpoint', text: 'Revert', action: revertToMessage},\n"
		"    {label: 'Retry or edit prompt', text: 'Retry', action: retryMessage},\n"
		"    {label: 'Delete this message', text: 'Delete', action: deleteMessage}\n"
		"  ].forEach(function(item) {\n"
		"    let button = document.createElement('button');\n"
		"    button.type = 'button';\n"
		"    button.className = 'msg-act-btn';\n"
		"    button.title = item.label;\n"
		"    button.textContent = item.text;\n"
		"    button.addEventListener('click', function() { item.action(button); });\n"
		"    actionsEl.appendChild(button);\n"
		"  });\n"
		"\n"
		"  contentBox.appendChild(senderEl);\n"
		"  contentBox.appendChild(bubble);\n"
		"  contentBox.appendChild(actionsEl);\n"
		"  row.appendChild(avatar);\n"
		"  row.appendChild(contentBox);\n"
		"  thread.appendChild(row);\n"
		"\n"
		"  ChatPagination.update();\n"
		"  return bubble;\n"
		"}\n"
		"\n"
		"function startChatStream(sessionId, promptText) {\n"
		"  let btnSend = document.getElementById('btn-send');\n"
		"  if (btnSend) btnSend.disabled = true;\n"
		"  currentStreamBuffer = '';\n"
		"  currentStreamBubble = appendMessage('assistant', 'Local demo response (not an AI model)', '', true);\n"
		"  let roleEl = document.getElementById('select-role');\n"
		"  let role = roleEl ? roleEl.value : 'pair-programmer';\n"
		"  let url = '/api/chat/stream/' + encodeURIComponent(sessionId) + '?prompt=' + encodeURIComponent(promptText) + '&role=' + encodeURIComponent(role);\n"
		"  if (eventSource) eventSource.close();\n"
		"  eventSource = new EventSource(url);\n"
		"  eventSource.onmessage = function(e) {\n"
		"    try {\n"
		"      let data = JSON.parse(e.data);\n"
		"      if (data.type === 'token') {\n"
		"        currentStreamBuffer += data.delta;\n"
		"        if (currentStreamBubble) {\n"
		"          let bodyEl = currentStreamBubble.querySelector('.markdown-body') || currentStreamBubble;\n"
		"          setMessageText(bodyEl, currentStreamBuffer, true);\n"
		"          let rawEl = currentStreamBubble.querySelector('.raw-markdown');\n"
		"          if (rawEl) rawEl.value = currentStreamBuffer;\n"
		"          scrollToBottom();\n"
		"        }\n"
		"      } else if (data.type === 'done') {\n"
		"        if (currentStreamBubble) {\n"
		"          let bodyEl = currentStreamBubble.querySelector('.markdown-body') || currentStreamBubble;\n"
		"          setMessageText(bodyEl, currentStreamBuffer, false);\n"
		"          let rawEl = currentStreamBubble.querySelector('.raw-markdown');\n"
		"          if (rawEl) rawEl.value = currentStreamBuffer;\n"
		"        }\n"
		"        eventSource.close();\n"
		"        eventSource = null;\n"
		"        if (btnSend) btnSend.disabled = false;\n"
		"        ChatPagination.update();\n"
		"      }\n"
		"    } catch(err) {\n"
		"      console.error('SSE JSON error', err);\n"
		"    }\n"
		"  };\n"
		"  eventSource.onerror = function() {\n"
		"    if (eventSource) eventSource.close();\n"
		"    eventSource = null;\n"
		"    if (btnSend) btnSend.disabled = false;\n"
		"    if (currentStreamBubble && currentStreamBuffer.length === 0) {\n"
		"      let bodyEl = currentStreamBubble.querySelector('.markdown-body') || currentStreamBubble;\n"
		"      bodyEl.textContent = 'Local demo response unavailable.';\n"
		"    }\n"
		"  };\n"
		"}\n"
		"\n"
		"function sendActualMessage(sessionId, text) {\n"
		"  fetch('/api/chat/message', {\n"
		"    method: 'POST',\n"
		"    headers: {'Content-Type': 'application/json'},\n"
		"    body: JSON.stringify({session_id: sessionId, content: text})\n"
		"  }).then(function(r) { return r.json(); }).then(function(data) {\n"
		"    startChatStream(sessionId, text);\n"
		"  }).catch(function(err) {\n"
		"    console.error('Send message error:', err);\n"
		"    startChatStream(sessionId, text);\n"
		"  });\n"
		"}\n"
		"\n"
		"function sendMessage() {\n"
		"  let input = document.getElementById('chat-input');\n"
		"  let text = input.value.trim();\n"
		"  if (!text) return;\n"
		"  ChatPagination.currentPage = 'live';\n"
		"  appendMessage('user', 'Human Operator', text, false);\n"
		"  input.value = '';\n"
		"  input.style.height = '48px';\n"
		"  if (!currentSessionId) {\n"
		"    let modeEl = document.getElementById('select-role');\n"
		"    let mode = modeEl ? modeEl.value : 'pair-programmer';\n"
		"    fetch('/api/chat/sessions/create', {\n"
		"      method: 'POST',\n"
		"      headers: {'Content-Type': 'application/json'},\n"
		"      body: JSON.stringify({title: 'Pair-Programming ' + new Date().toLocaleTimeString(), pair_mode: mode})\n"
		"    }).then(function(r) { return r.json(); }).then(function(data) {\n"
		"      if (data.session && data.session.id) {\n"
		"        currentSessionId = data.session.id;\n"
		"      } else {\n"
		"        currentSessionId = 'sess-default';\n"
		"      }\n"
		"      sendActualMessage(currentSessionId, text);\n"
		"    }).catch(function(err) {\n"
		"      console.error('Session create error:', err);\n"
		"      currentSessionId = 'sess-default';\n"
		"      sendActualMessage(currentSessionId, text);\n"
		"    });\n"
		"  } else {\n"
		"    sendActualMessage(currentSessionId, text);\n"
		"  }\n"
		"}\n"
		"\n"
		"function sendQuickAction(actionText) {\n"
		"  let input = document.getElementById('chat-input');\n"
		"  input.value = actionText;\n"
		"  sendMessage();\n"
		"}\n"
		"\n"
		"function selectSession(id) {\n"
		"  currentSessionId = id;\n"
		"  window.location.href = '/chat?session=' + encodeURIComponent(id);\n"
		"}\n"
		"\n"
		"function newSession() {\n"
		"  let modeEl = document.getElementById('select-role');\n"
		"  let mode = modeEl ? modeEl.value : 'pair-programmer';\n"
		"  fetch('/api/chat/sessions/create', {\n"
		"    method: 'POST',\n"
		"    headers: {'Content-Type': 'application/json'},\n"
		"    body: JSON.stringify({title: 'Pair-Programming ' + new Date().toLocaleTimeString(), pair_mode: mode})\n"
		"  }).then(r => r.json()).then(data => {\n"
		"    if (data.session && data.session.id) {\n"
		"      selectSession(data.session.id);\n"
		"    }\n"
		"  });\n"
		"}\n"
		"\n"
		"document.addEventListener('DOMContentLoaded', function() {\n"
		"  document.querySelectorAll('.session-item[data-session-id]').forEach(function(item) {\n"
		"    item.addEventListener('click', function() { selectSession(item.getAttribute('data-session-id')); });\n"
		"  });\n"
		"  ChatPagination.update();\n"
		"  let input = document.getElementById('chat-input');\n"
		"  if (input) {\n"
		"    input.addEventListener('keydown', function(e) {\n"
		"      if (e.key === 'Enter' && !e.shiftKey) {\n"
		"        e.preventDefault();\n"
		"        sendMessage();\n"
		"      }\n"
		"    });\n"
		"  }\n"
		"  scrollToBottom();\n"
		"});\n"
		"window.addEventListener('load', function() {\n"
		"  ChatPagination.update();\n"
		"});\n";
	return s;
}

