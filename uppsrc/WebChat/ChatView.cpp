static String EscapeChatHtml(const String& text)
{
	String out;
	for(int i = 0; i < text.GetCount(); i++) {
		byte c = (byte)text[i];
		if(c < 0x20 || c == 0x7f) {
			out << "&#xfffd;";
			continue;
		}
		switch(text[i]) {
		case '&':  out << "&amp;"; break;
		case '<':  out << "&lt;"; break;
		case '>':  out << "&gt;"; break;
		case '"':  out << "&quot;"; break;
		case '\'': out << "&#39;"; break;
		default:   out.Cat(text[i]); break;
		}
	}
	return out;
}

